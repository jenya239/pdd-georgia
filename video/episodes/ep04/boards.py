def card(d, x, y, w, q, cite, a, sz=15):
    return quote(d, x, y, w, q, cite, a, sz, INK, CARD)

def lane(img, d, x0, x1, y):
    return road(img, d, x0, x1, y, [("sidewalk", 22, 0), ("lane", 62, 1), ("lane", 62, -1), ("sidewalk", 22, 0)])

def zebra(d, x0, x1, y0, y1, a=1.0):
    if a <= 0:
        return
    x = x0
    while x < x1:
        d.rectangle([x * SS, y0 * SS, min(x + 14, x1) * SS, y1 * SS], fill=(245, 245, 245, int(255 * a)))
        x += 28

def zone(d, x0, x1, y0, y1, a, col=(205, 40, 30)):
    if a <= 0:
        return
    d.rectangle([x0 * SS, y0 * SS, x1 * SS, y1 * SS], fill=col + (int(70 * a),))


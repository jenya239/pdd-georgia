# ПДД ep08 boards. Цитаты ст. 5, п. 14 и п. 84 — дословно.
Q14 = ("Уступить дорогу (не создавать помех) – обязательство участников дорожного движения не продолжать "
       "или не возобновлять движение либо не осуществлять маневр, если это вынудит участников движения "
       "с преимуществом (приоритетом) неожиданно изменить направление или скорость движения.")
Q84 = ("Преимущество (приоритет) – право участника дорожного движения на первоочередное движение "
       "в намеченном направлении по отношению к другим участникам дорожного движения.")

def cross(img, d, y):
    return road(img, d, 80, 1160, y, [("verge", 16, 0), ("lane", 64, 1), ("lane", 64, -1), ("verge", 16, 0)])

def b_close(img, d, t, B, D):
    txt(d, (30, 16), "Зелёный обоим, поворот налево", 22, WHITE, 1, "la", DJB)
    ys = cross(img, d, 70)
    car_top(d, 360, (ys[1][0] + ys[1][1]) / 2, 1, (60, 110, 200), 1)
    car_top(d, 860, (ys[2][0] + ys[2][1]) / 2, -1, (200, 80, 70), 1)
    if t > B.S(1) - 0.2:
        chip(d, 40, 250, "близко — поворот не начинают", RED, appear(t, B.S(1)), 18)

def b_far(img, d, t, B, D):
    txt(d, (30, 16), "Та же схема, другая даль и скорость", 22, WHITE, 1, "la", DJB)
    ys = cross(img, d, 70)
    car_top(d, 280, (ys[1][0] + ys[1][1]) / 2, 1, (60, 110, 200), 1)
    car_top(d, 1080, (ys[2][0] + ys[2][1]) / 2, -1, (200, 80, 70), appear(t, 0.3))
    if t > B.S(1) - 0.2:
        chip(d, 40, 240, "далеко и небыстро — ждать не нужно", GREEN, appear(t, B.S(1)), 18)
    if t > B.S(2) - 0.2:
        chip(d, 40, 290, "та же даль, высокая скорость — поворот не начинают", RED, appear(t, B.S(2)), 18)

def b_yield(img, d, t, B, D):
    txt(d, (30, 16), "Уступить — ст. 5, п. 14", 22, WHITE, 1, "la", DJB)
    y = quote(d, 30, 56, 1180, Q14, "ст. 5, п. 14", appear(t, 0.2), 16)
    if t > B.S(1) - 0.2:
        chip(d, 30, y + 12, "продолжать и возобновлять — тоже, не только начать поворот", GOLD, appear(t, B.S(1)), 16)

def b_priority(img, d, t, B, D):
    txt(d, (30, 16), "Преимущество — ст. 5, п. 84", 22, WHITE, 1, "la", DJB)
    y = quote(d, 30, 56, 1180, Q84, "ст. 5, п. 84", appear(t, 0.2), 16)
    if t > B.S(2) - 0.2:
        chip(d, 30, y + 12, "намерение показывают скоростью или остановкой", GOLD, appear(t, B.S(2)), 16)
    if t > B.S(3) - 0.2:
        chip(d, 30, y + 58, "право первым не отменяет опасность", RED, appear(t, B.S(3)), 16)

def b_outro(img, d, t, B, D):
    txt(d, (30, 24), "Кто первый, затем даль и скорость", 22, WHITE, 1, "la", DJB)
    chip(d, 40, 120, "уступить — не заставить неожиданно менять скорость или направление", GOLD, appear(t, 0.3), 18)

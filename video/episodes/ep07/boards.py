Q11 = ("Остановка – преднамеренное прекращение движения транспортного средства на время до 5 минут "
       "или на более длительное время, если это необходимо для посадки или высадки пассажиров "
       "либо для загрузки или разгрузки транспортного средства.")
Q11B = ("Остановкой не считается преднамеренное прекращение движения транспортного средства "
        "в транспортном потоке, по требованию технических средств организации дорожного движения или регулировщика.")
Q20 = ("Стоянка – преднамеренное прекращение движения транспортного средства на время более 5 минут, "
       "если это необходимо для посадки или высадки пассажиров либо для загрузки или разгрузки транспортного средства.")
Q26 = ("Вынужденная остановка – прекращение движения транспортного средства ввиду его технической неисправности, "
       "опасности, созданной перевозимым грузом, состоянием водителя (пассажира) или неожиданным появлением препятствия на дороге.")

def lane(img, d, y):
    return road(img, d, 40, 1200, y, [("sidewalk", 18, 0), ("lane", 70, 1), ("lane", 70, -1), ("sidewalk", 18, 0)])

def b_short(img, d, t, B, D):
    txt(d, (30, 18), "Две минуты у магазина", 22, WHITE, 1, "la", DJB)
    ys = lane(img, d, 70)
    car_top(d, 420, (ys[1][0] + ys[1][1]) / 2, 1, (60, 110, 200), 1)
    if t > B.S(1) - 0.2:
        chip(d, 40, 250, "до пяти минут — остановка, цель не спрашивают", GOLD, appear(t, B.S(1)), 18)

def b_quote_stop(img, d, t, B, D):
    txt(d, (30, 16), "Остановка — ст. 5, п. 11", 22, WHITE, 1, "la", DJB)
    y = quote(d, 30, 56, 1180, Q11, "ст. 5, п. 11", appear(t, 0.2), 16)
    if t > B.S(1) - 0.2:
        chip(d, 30, y + 12, "дольше пяти минут ради погрузки — всё ещё остановка", GREEN, appear(t, B.S(1)), 16)

def b_park(img, d, t, B, D):
    txt(d, (30, 16), "Десять минут не ради погрузки", 22, WHITE, 1, "la", DJB)
    ys = lane(img, d, 64)
    car_top(d, 420, (ys[1][0] + ys[1][1]) / 2, 1, (60, 110, 200), 1)
    y = quote(d, 30, 250, 1180, Q20, "ст. 5, п. 20, русский текст", appear(t, B.S(1)), 15)
    if t > B.S(2) - 0.2:
        chip(d, 30, y + 8, "в переводе пропущено «не»", RED, appear(t, B.S(2)), 16)


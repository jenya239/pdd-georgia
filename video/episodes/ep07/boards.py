def b_outro(img, d, t, B, D):
    txt(d, (30, 22), "Срок, цель, причина", 22, WHITE, 1, "la", DJB)
    rows = [
        (B.S(0), "до 5 минут или дольше ради посадки — остановка"),
        (B.S(1), "дольше 5 минут и не ради посадки — стоянка"),
        (B.S(2), "поломка, груз, люди, внезапное препятствие — вынужденная"),
    ]
    for i, (tt, text) in enumerate(rows):
        chip(d, 40, 90 + i * 70, text, GOLD if i == 1 else BLUE, appear(t, tt), 18)

def b_tram(img, d, t, B, D):
    txt(d, (30, 16), "Равнозначный перекрёсток", 22, WHITE, 1, "la", DJB)
    ys = cross(img, d, 64)
    car_top(d, 360, (ys[1][0] + ys[1][1]) / 2, 1, (60, 110, 200), 1)
    car_top(d, 820, (ys[2][0] + ys[2][1]) / 2, -1, (40, 40, 48), 1)
    y = quote(d, 30, 230, 1180, Q36, "ст. 36, п. 4 «в»", appear(t, B.S(0)), 16)

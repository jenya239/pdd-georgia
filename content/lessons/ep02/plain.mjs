/** Выпуск 2, редакция без персонажей. Ролик с диалогом остаётся отдельно. */
import { MARKER, lesson, lq } from "../html.mjs";

const DEFS = `<defs><pattern id="ep02-hatch" width="8" height="8" patternUnits="userSpaceOnUse"><path d="M0 8 L8 0" class="move"/></pattern></defs>`;

function fig(label, body, cap, defs = "") {
  return `<figure class="fig"><svg viewBox="0 0 640 280" role="img" aria-label="${label}" xmlns="http://www.w3.org/2000/svg">${defs}${body}</svg><figcaption>${cap}</figcaption></figure>`;
}

function t(y, text) {
  return `<text x="8" y="${y}" class="t small">${text}</text>`;
}

function band(cls, y, h) {
  return `<rect x="148" y="${y}" width="476" height="${h}" class="${cls}"/>`;
}

function shoulder(y) {
  return band("bed", y, 28) + `<rect x="148" y="${y}" width="476" height="28" fill="url(#ep02-hatch)" opacity="0.45"/>`;
}

function dash(y) {
  return `<line x1="148" y1="${y}" x2="624" y2="${y}" class="paint dash"/>`;
}

function car(y) {
  return `<rect class="car" x="360" y="${y}" width="52" height="18" rx="3"/>`;
}

function person(x, y) {
  return `<circle class="head" cx="${x}" cy="${y}" r="5"/><path class="ppl" d="M${x} ${y + 5} v12 M${x} ${y + 9} l-7 5 M${x} ${y + 9} l7 5 M${x} ${y + 17} l-5 8 M${x} ${y + 17} l5 8"/>`;
}

function bike(x, y) {
  return `<circle class="ppl" cx="${x}" cy="${y}" r="7"/><circle class="ppl" cx="${x + 20}" cy="${y}" r="7"/><path class="ppl" d="M${x} ${y} l10 -10 10 10"/>`;
}

function parts(withDash) {
  return band("walk", 8, 36) + shoulder(44) + band("road", 72, 56) + (withDash ? dash(100) : "")
    + band("verge", 128, 24) + band("road", 152, 56) + (withDash ? dash(180) : "")
    + shoulder(208) + band("walk", 236, 36)
    + t(30, "тротуар") + t(62, "обочина") + t(104, "проезжая")
    + t(144, "разделитель") + t(184, "проезжая") + t(226, "обочина") + t(258, "тротуар");
}

function sketchRoad() {
  return fig(
    "Дорога шире проезжей части",
    band("bed", 8, 264) + band("road", 72, 136) + t(30, "дорога") + t(148, "проезжая часть"),
    "Проезжая часть лежит внутри дороги. Тротуар и обочина тоже относятся к дороге, но автомобиль едет не по ним.",
    DEFS,
  );
}

function sketchParts() {
  return fig(
    "Тротуар, обочина и разделительная полоса на той же дороге",
    parts(true),
    "Тротуар и обочина входят в дорогу и не входят в проезжую часть. Построенная разделительная полоса делит дорогу на две проезжие части. Линия между рядами этого не делает.",
  );
}

function sketchLanes() {
  return fig(
    "Та же дорога без линий разметки: ширина проезжей части держит два ряда",
    parts(false) + car(158) + car(184),
    "Разметки между рядами нет, но ширина проезжей части по-прежнему вмещает два ряда автомобилей. Направление движения от этого не меняется.",
  );
}

function sketchWho() {
  return fig(
    "Машина на проезжей части, пешеход на тротуаре, велосипед на обочине",
    parts(true) + person(380, 14) + bike(370, 58) + car(158),
    "Автомобиль остаётся на проезжей части, пешеход — на тротуаре. Велосипед без своей полосы или дорожки может ехать по обочине по ходу движения, если не мешает остальным.",
  );
}

